def _delete_paragraph(para) -> None:
    element = para._element
    parent = element.getparent()
    if parent is not None:
        parent.remove(element)


def _set_plain_bold_label(para, text: str) -> None:
    para.style = "Normal"
    _replace_paragraph_text(para, text)
    for run in para.runs:
        _format_run(run, bold=True)


def _replace_terms_everywhere(doc: Document, replacements: dict[str, str]) -> None:
    for para in doc.paragraphs:
        text = para.text
        new_text = text
        for old, new in replacements.items():
            new_text = new_text.replace(old, new)
        if new_text != text:
            _replace_paragraph_text(para, new_text)
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    text = para.text
                    new_text = text
                    for old, new in replacements.items():
                        new_text = new_text.replace(old, new)
                    if new_text != text:
                        _replace_paragraph_text(para, new_text)


