def _find_paragraph(doc: Document, prefix: str, *, style_prefix: str | None = None):
    for para in doc.paragraphs:
        if style_prefix is not None and not para.style.name.startswith(style_prefix):
            continue
        if para.text.strip().startswith(prefix):
            return para
    return None


def _find_table_after_paragraph(doc: Document, para):
    body = doc._body._element
    seen_anchor = False
    for child in body:
        if child is para._p:
            seen_anchor = True
            continue
        if seen_anchor and child.tag.endswith("tbl"):
            for table in doc.tables:
                if table._tbl is child:
                    return table
            return None
    return None


def _insert_after_caption_or_following_table(doc: Document, caption: str, text: str) -> None:
    para = _find_paragraph(doc, caption)
    if para is None:
        return
    _insert_paragraph_after(doc, para, text)


