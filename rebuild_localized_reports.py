def _apply_rtl(doc):
    """Apply RTL formatting for Arabic."""
    for style_name in ["Normal", "List Bullet", "List Number", "List Paragraph"]:
        try:
            s = doc.styles[style_name]
            s.font.name = "Arial"
            pPr = s.element.get_or_add_pPr()
            existing_bidi = pPr.findall(qn("w:bidi"))
            if not existing_bidi:
                bidi = pPr.makeelement(qn("w:bidi"), {})
                pPr.append(bidi)
        except KeyError:
            pass

    for hs in range(1, 10):
        try:
            s = doc.styles[f"Heading {hs}"]
            s.font.name = "Arial"
            pPr = s.element.get_or_add_pPr()
            existing_bidi = pPr.findall(qn("w:bidi"))
            if not existing_bidi:
                bidi = pPr.makeelement(qn("w:bidi"), {})
                pPr.append(bidi)
        except KeyError:
            pass

    for para in doc.paragraphs:
        if para.alignment != WD_ALIGN_PARAGRAPH.CENTER:
            para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        pPr = para._element.get_or_add_pPr()
        existing_bidi = pPr.findall(qn("w:bidi"))
        if not existing_bidi:
            bidi = pPr.makeelement(qn("w:bidi"), {})
            pPr.append(bidi)
        for run in para.runs:
            run.font.name = "Arial"


def translate_report(lang_map: dict, out_name: str, is_rtl: bool = False):
    """Create a translated copy of the English report."""
    doc = Document(str(EN_REPORT))
    
    translated = 0
    skipped = 0
    
    for para in doc.paragraphs:
        text = para.text.strip()
        if not text:
            continue
        
        translation = _find_translation(text, lang_map)
        if translation:
            _replace_paragraph_text(para, translation)
            translated += 1
        else:
            skipped += 1
    
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    text = para.text.strip()
                    if not text:
                        continue
                    if "SARIMAX" in text:
                        _replace_paragraph_text(para, text.replace("SARIMAX", "SARIMA"))

    if out_name == "project_report_RU.docx":
        _restructure_ru_stage_b(doc)
        _insert_ru_requested_figure_table_explanations(doc)
        _insert_ru_forecast_error_sections(doc)
    
    if is_rtl:
        _apply_rtl(doc)
    
    out_path = ROOT / "outputs" / "reports" / out_name
    out_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        doc.save(str(out_path))
    except PermissionError:
        fallback = out_path.with_name(out_path.stem + "_updated.docx")
        doc.save(str(fallback))
        print(
            f"  Warning: {out_path} is locked. Saved updated copy as: {fallback}",
            file=sys.stderr,
        )
        out_path = fallback
    
    n_para = len([p for p in doc.paragraphs if p.text.strip()])
    n_headings = len([p for p in doc.paragraphs if p.style.name.startswith("Heading")])
    n_tables = len(doc.tables)
    n_images = len(doc.inline_shapes)
    
    print(f"  Saved: {out_path}")
    print(f"  Translated: {translated}, Kept original: {skipped}")
    print(f"  Paragraphs: {n_para}, Headings: {n_headings}, Tables: {n_tables}, Images: {n_images}")
    print(f"  Size: {out_path.stat().st_size / 1024:.1f} KB")


