def _find_translation(text: str, lang_map: dict) -> str | None:
    """Find translation by matching first N chars of text to keys."""
    text_clean = text.strip()
    if not text_clean:
        return None
    for key, val in lang_map.items():
        if text_clean.startswith(key) or key.startswith(text_clean[:30]):
            return val
    return None


def _replace_paragraph_text(para, new_text: str):
    """Replace all text in a paragraph while preserving first run's formatting."""
    if not para.runs:
        para.text = new_text
        return
    first_run = para.runs[0]
    for run in para.runs[1:]:
        run._element.getparent().remove(run._element)
    first_run.text = new_text


def _format_run(run, *, italic: bool = False, bold: bool = False) -> None:
    run.font.name = "Times New Roman"
    run.font.size = Pt(12)
    run.italic = italic
    run.bold = bold
    try:
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    except Exception:
        pass


def _insert_paragraph_after(doc: Document, anchor, text: str, *, italic: bool = False, bold: bool = False, align=None):
    para = doc.add_paragraph()
    run = para.add_run(text)
    _format_run(run, italic=italic, bold=bold)
    if align is not None:
        para.alignment = align
    anchor._p.addnext(para._p)
    return para


def _insert_heading_after(doc: Document, anchor, text: str, level: int):
    para = doc.add_heading(text, level=level)
    for run in para.runs:
        _format_run(run, bold=run.bold)
    anchor._p.addnext(para._p)
    return para


